/**
 * Security headers for the deployed site — the single source of truth.
 *
 * The build writes them to `dist/_headers` (Netlify / Cloudflare Pages format) and the
 * local `vite preview` serves the same policy, so the CSP is exercised in tests.
 * For other hosts, copy the values from `dist/_headers` (see docs/deployment.md).
 */
export type CaptchaProviderName = 'turnstile' | 'hcaptcha' | null;

export interface HeaderOptions {
  /** VITE_SUPABASE_URL, e.g. https://abcd.supabase.co (or http://127.0.0.1:54321 locally). */
  supabaseUrl: string;
  captcha: CaptchaProviderName;
  /** HSTS only makes sense over HTTPS (never for the local preview). */
  https: boolean;
}

const CAPTCHA_ORIGINS: Record<'turnstile' | 'hcaptcha', string[]> = {
  turnstile: ['https://challenges.cloudflare.com'],
  hcaptcha: ['https://hcaptcha.com', 'https://*.hcaptcha.com'],
};

export function contentSecurityPolicy({ supabaseUrl, captcha }: HeaderOptions): string {
  const api = new URL(supabaseUrl);
  const ws = `${api.protocol === 'https:' ? 'wss:' : 'ws:'}//${api.host}`;
  const captchaOrigins = captcha ? CAPTCHA_ORIGINS[captcha] : [];
  const directives: Record<string, string[]> = {
    'default-src': ["'self'"],
    'script-src': ["'self'", ...captchaOrigins],
    // React sets a few inline style attributes (animation delays, confetti); no user HTML
    // is ever rendered, so inline styles carry no injection risk here.
    'style-src': ["'self'", "'unsafe-inline'", ...(captcha === 'hcaptcha' ? captchaOrigins : [])],
    'img-src': ["'self'", 'data:'],
    'font-src': ["'self'"],
    // Supabase REST/Auth (https) and Realtime (wss) — nothing else.
    'connect-src': ["'self'", api.origin, ws, ...(captcha === 'hcaptcha' ? captchaOrigins : [])],
    'frame-src': captchaOrigins.length ? captchaOrigins : ["'none'"],
    'worker-src': ["'none'"],
    'object-src': ["'none'"],
    'base-uri': ["'self'"],
    'form-action': ["'self'"],
    'frame-ancestors': ["'none'"],
  };
  return Object.entries(directives)
    .map(([name, values]) => `${name} ${values.join(' ')}`)
    .join('; ');
}

export function securityHeaders(options: HeaderOptions): Record<string, string> {
  return {
    'Content-Security-Policy': contentSecurityPolicy(options),
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'X-Frame-Options': 'DENY',
    // Nothing sensitive is needed; Web Audio needs no permission.
    'Permissions-Policy':
      'camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
    ...(options.https
      ? { 'Strict-Transport-Security': 'max-age=63072000; includeSubDomains' }
      : {}),
  };
}

/** `_headers` file content (Netlify / Cloudflare Pages). */
export function headersFile(options: HeaderOptions): string {
  const lines = Object.entries(securityHeaders(options)).map(([k, v]) => `  ${k}: ${v}`);
  return [
    '# Generated by the build (deploy/security-headers.ts). Do not edit by hand.',
    '/*',
    ...lines,
    '',
    '# Hashed assets never change: cache them for a year.',
    '/assets/*',
    '  Cache-Control: public, max-age=31536000, immutable',
    '',
    '# The HTML must always be revalidated so a new deploy is picked up.',
    '/index.html',
    '  Cache-Control: no-cache',
    '',
  ].join('\n');
}

/** SPA fallback: every route is served by index.html (client-side routing). */
export const REDIRECTS_FILE = '/*    /index.html   200\n';
